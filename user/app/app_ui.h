#ifndef __APP_UI_H
#define __APP_UI_H
/**
 * ============================================================
 * 表现层：本地人机界面（按键 / 彩屏 / 蜂鸣器 / 状态灯）
 *
 *   按键（4 键，短按/长按）：
 *     OK   长按 = 急停；标定模式短按 = 保存
 *     UP/DOWN 标定模式短按 +/-1、长按 +/-100
 *     BACK 短按 = 清故障；长按 = 进入/退出标定
 *
 *   指示灯（WS2812 ×3）：空闲蓝 / 移动绿 / 故障红闪
 *   屏幕：状态、预测格号、目标格号、每格脉冲数、5V/USB
 * ============================================================
 */
#include <stdint.h>

void Ui_Init(void);
void Ui_Tick(void);        /* 10ms：按键扫描与事件处理 */
void Ui_Refresh(void);     /* 100ms：屏幕与指示灯刷新 */

#endif /* __APP_UI_H */
