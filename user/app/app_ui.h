#ifndef __APP_UI_H
#define __APP_UI_H
/**
 * ============================================================
 * 表现层：本地人机界面（按键 / 彩屏 / 蜂鸣器 / 状态灯）
 *
 *   按键（4 键，短按/长按）：
 *     OK   短按 = 出药 1 粒        长按 = 急停
 *     UP   短按 = 回零
 *     DOWN 短按 = 清除故障
 *     BACK 短按 = 5V 开/关切换     长按 = 关闭 5V（软关机）
 *
 *   指示灯（WS2812 ×3）：空闲蓝 / 回零黄 / 出药绿 / 故障红闪
 *   屏幕：状态、错误码、位置步数、最近出药粒数、参数、5V/USB/限位
 * ============================================================
 */
#include <stdint.h>

void Ui_Init(void);
void Ui_Tick(void);        /* 10ms：按键扫描与事件处理 */
void Ui_Refresh(void);     /* 100ms：屏幕与指示灯刷新 */

#endif /* __APP_UI_H */
